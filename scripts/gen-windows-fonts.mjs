#!/usr/bin/env node
// Generate backend/src/runtime/windowsFontPrefs.ts from Chromium's Windows
// locale font defaults (locale_settings_win.grd + xtb) resolved against the
// packaged Windows fonts (third_party/assets/windows-fonts).
//
//   node scripts/gen-windows-fonts.mjs [--chromium=browser/.portablelinux/build/src]
import { execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, '').split('=')));
const SRC = path.resolve(args.chromium || path.join(ROOT, 'browser/.portablelinux/build/src'));
const FONT_DIR = path.join(ROOT, 'third_party/assets/windows-fonts');
const OUT = path.join(ROOT, 'backend/src/runtime/windowsFontPrefs.ts');

/** Files shipped by Windows 11 but not by Windows 10 22H2. */
const WIN11_ONLY_FILES = [
  'CascadiaCode.ttf',
  'CascadiaMono.ttf',
  'NotoSansSC-VF.ttf',
  'NotoSerifSC-VF.ttf',
  'SansSerifCollection.ttf',
  'SegUIVar.ttf',
  'SegoeIcons.ttf',
];

const GENERIC = {
  STANDARD: 'standard',
  FIXED: 'fixed',
  SERIF: 'serif',
  SANS_SERIF: 'sansserif',
  CURSIVE: 'cursive',
  FANTASY: 'fantasy',
  MATH: 'math',
};
const SCRIPTS = {
  ARABIC: 'Arab',
  CYRILLIC: 'Cyrl',
  GREEK: 'Grek',
  JAPANESE: 'Jpan',
  KOREAN: 'Kore',
  SIMPLIFIED_HAN: 'Hans',
  TRADITIONAL_HAN: 'Hant',
  DEVANAGARI: 'Deva',
};

function scanFamilies(exclude) {
  const out = execFileSync('fc-scan', ['--format', '%{file}\t%{family}\n', FONT_DIR], { encoding: 'utf8' });
  const families = new Set();
  for (const line of out.split('\n')) {
    const [file, fams] = line.split('\t');
    if (!file || exclude.includes(path.basename(file))) continue;
    for (const f of String(fams || '').split(',')) families.add(f.trim().toLowerCase());
  }
  return families;
}

function parseMessages(xml) {
  const out = {};
  for (const m of xml.matchAll(/<message name="(IDS_\w+)"[^>]*>\s*([\s\S]*?)\s*<\/message>/g)) out[m[1]] = m[2].trim();
  for (const m of xml.matchAll(/<translation id="(IDS_\w+)">([\s\S]*?)<\/translation>/g)) out[m[1]] = m[2].trim();
  return out;
}

/** Chromium "font list" values start with ','; take the first installed family. */
function resolve(value, families) {
  if (!value) return undefined;
  if (!value.startsWith(',')) return value;
  const list = value.slice(1).split(',').map((s) => s.trim()).filter(Boolean);
  return list.find((f) => families.has(f.toLowerCase())) || list[list.length - 1];
}

function prefsFor(messages, families, locale) {
  const generic = {};
  for (const [id, key] of Object.entries(GENERIC)) {
    const v = resolve((locale && locale[`IDS_${id}_FONT_FAMILY`]) || messages[`IDS_${id}_FONT_FAMILY`], families);
    if (v) generic[key] = v;
  }
  const alt = messages.IDS_FIXED_FONT_FAMILY_ALT_WIN;
  if (alt && generic.fixed === messages.IDS_FIXED_FONT_FAMILY && !locale?.IDS_FIXED_FONT_FAMILY) generic.fixed = alt;
  return generic;
}

function main() {
  const grdPath = path.join(SRC, 'chrome/app/resources/locale_settings_win.grd');
  const grd = fs.readFileSync(grdPath, 'utf8');
  const base = parseMessages(grd);
  const xtbDir = path.join(SRC, 'chrome/app/resources/platform_locale_settings');
  const locales = {};
  for (const file of fs.readdirSync(xtbDir).filter((f) => /^locale_settings_win_.+\.xtb$/.test(f))) {
    const lang = file.replace(/^locale_settings_win_|\.xtb$/g, '');
    const msgs = parseMessages(fs.readFileSync(path.join(xtbDir, file), 'utf8'));
    if (Object.keys(msgs).some((k) => k.endsWith('_FONT_FAMILY'))) locales[lang] = msgs;
  }

  const releases = {};
  for (const release of ['win10', 'win11']) {
    const families = scanFamilies(release === 'win10' ? WIN11_ONLY_FILES : []);
    const scripts = {};
    for (const [name, script] of Object.entries(SCRIPTS)) {
      const row = {};
      for (const [id, key] of Object.entries(GENERIC)) {
        const v = resolve(base[`IDS_${id}_FONT_FAMILY_${name}`], families);
        if (v) row[key] = v;
      }
      if (Object.keys(row).length) scripts[script] = row;
    }
    const byLocale = {};
    for (const [lang, msgs] of Object.entries(locales).sort()) byLocale[lang] = prefsFor(base, families, msgs);
    releases[release] = { defaults: prefsFor(base, families, null), locales: byLocale, scripts };
  }

  const body = `// Generated by scripts/gen-windows-fonts.mjs from Chromium ${fs
    .readFileSync(path.join(ROOT, 'browser/VERSION'), 'utf8')
    .trim()} locale_settings_win and third_party/assets/windows-fonts. Do not edit.

export type WindowsGenericFonts = Partial<Record<'standard' | 'fixed' | 'serif' | 'sansserif' | 'cursive' | 'fantasy' | 'math', string>>;

export interface WindowsFontPrefs {
  defaults: WindowsGenericFonts;
  locales: Record<string, WindowsGenericFonts>;
  scripts: Record<string, WindowsGenericFonts>;
}

export const WIN11_ONLY_FONT_FILES: readonly string[] = ${JSON.stringify(WIN11_ONLY_FILES)};

export const WINDOWS_FONT_PREFS: Record<'win10' | 'win11', WindowsFontPrefs> = ${JSON.stringify(releases, null, 2)};
`;
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

main();
